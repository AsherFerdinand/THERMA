function output = compare_boptest_c28(indexFile,referenceFolder)
%COMPARE_BOPTEST_C28 Read-only C2.7 air-temperature comparison; no simulations.
root=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
if nargin<1 || strlength(string(indexFile))==0
    candidates=dir(fullfile(root,'outputs','boptest','c27','*','study_index.json'));
    assert(numel(candidates)==1,'THERMA:C28Study', ...
        'Expected one C2.7 study; pass its study_index.json path explicitly. Found %d.',numel(candidates));
    indexFile=fullfile(candidates(1).folder,candidates(1).name);
end
if nargin<2, referenceFolder=fullfile(root,'outputs','boptest','c28','reference'); end
assert(isfile(indexFile),'THERMA:C28Missing','Missing C2.7 study index: %s',indexFile);
index=jsondecode(fileread(indexFile)); session=fileparts(indexFile);
contractFile=fullfile(session,'contract.json');
assert(strcmp(index.status,'completed') && isfile(contractFile) && ...
    strcmp(boptest_file_sha256(contractFile),index.contract_sha256), ...
    'THERMA:C28Contract','Incomplete study or changed contract.');
contract=jsondecode(fileread(contractFile));
m=jsondecode(fileread(fullfile(referenceFolder,'reference_metadata.json')));
referenceFile=fullfile(referenceFolder,'reference_temperature.csv');
assert(strcmp(boptest_file_sha256(referenceFile),m.csv_sha256) && ...
    strcmp(boptest_file_sha256(fullfile(referenceFolder,'source_manifest.json')),m.source_manifest_sha256) && ...
    strcmp(boptest_file_sha256(fullfile(referenceFolder,'source_signals.json')),m.source_signals_sha256), ...
    'THERMA:C28Hash','Changed reference CSV or provenance artifacts.');
assert(strcmp(m.scenario.name,'typical_heat_day') && m.scenario.initialization_time_s==28252800 && ...
    m.scenario.evaluation_start_s==28857600 && m.scenario.evaluation_end_s==30067200 && ...
    ~m.scenario.reset_at_evaluation_start && strcmp(m.time_basis,'absolute_simulation_seconds'), ...
    'THERMA:C28Scenario','Reference scenario/time basis mismatch.');
ref=readTemperatureTable(referenceFile);
signals=m.signals; air=find(strcmp({signals.quantity},'air_temperature'));
assert(numel(air)==1 && strcmp(signals(air).unit,'K') && ...
    strcmp(signals(air).source,'mod.case900Template.TAir'), ...
    'THERMA:C28Quantity','Reference air unavailable; operative temperature cannot supply air metrics.');
t=ref.time_s; reference=ref.(signals(air).column)-273.15;
assert(numel(t)==40321 && numel(t)==m.sample_count && t(1)==28857600 && t(end)==30067200 && ...
    all(diff(t)==30) && all(isfinite(t)) && all(isfinite(reference)), ...
    'THERMA:C28Reference','Reference must contain complete finite native 30 s evaluation samples.');
ids={'no_solar_30','solar_30'}; values=zeros(numel(t),2); reports=cell(1,2); summaries=cell(1,2);
provenance=struct('index_sha256',boptest_file_sha256(indexFile), ...
    'reference_metadata_sha256',boptest_file_sha256(fullfile(referenceFolder,'reference_metadata.json')), ...
    'reference_csv_sha256',m.csv_sha256,'matlab_version',version);
for j=1:2
    item=index.experiments.(ids{j}); relative=char(item.folder);
    parts=strsplit(strrep(relative,'\','/'),'/');
    assert(~startsWith(relative,{'/','\'}) && ~contains(relative,':') && ...
        ~any(strcmp(parts,'..')),'THERMA:C28Path','Unsafe study folder.');
    folder=fullfile(fileparts(session),parts{:});
    receiptFile=fullfile(folder,'completion.json');
    assert(strcmp(item.status,'completed') && ...
        strcmp(boptest_file_sha256(receiptFile),item.completion_sha256), ...
        'THERMA:C28Receipt','Incomplete or changed completion receipt.');
    receipt=jsondecode(fileread(receiptFile)); expected=receipt.expected;
    assert(strcmp(receipt.status,'completed') && strcmp(expected.experiment_id,ids{j}) && ...
        expected.max_step_s==30 && strcmp(expected.contract_sha256,index.contract_sha256) && ...
        strcmp(expected.matlab_version,contract.matlab_version), ...
        'THERMA:C28Contract','Experiment does not match study contract.');
    names={'evaluation.csv','comparison_metadata.json','replay_run.json'};
    for k=1:numel(names)
        hit=find(strcmp({receipt.artifacts.name},names{k}));
        assert(numel(hit)==1 && strcmp(boptest_file_sha256(fullfile(folder,names{k})), ...
            receipt.artifacts(hit).sha256),'THERMA:C28Hash','Changed/missing comparison artifact: %s',names{k});
    end
    metadata=jsondecode(fileread(fullfile(folder,'comparison_metadata.json')));
    r=jsondecode(fileread(fullfile(folder,'replay_run.json'))); p=r.replay_metadata;
    driver=find(strcmp({contract.sources.name},'run_boptest_zone_replay.m'));
    assert(numel(driver)==1 && strcmp(r.driver_source_sha256,contract.sources(driver).sha256), ...
        'THERMA:C28Source','Driver source differs from execution contract.');
    assert(strcmp(r.status,'executed_partial_not_validated') && r.matlab_execution_completed && ...
        r.simulation_returned && strcmp(r.matlab_version,contract.matlab_version) && ...
        strcmp(r.replay_packet_sha256,expected.packet_sha256) && ...
        strcmp(r.registry_sha256,contract.frozen_registry_sha256) && ...
        strcmp(r.assumptions_sha256,contract.assumptions_sha256) && ...
        str2double(r.solver.MaxStep_s)==30,'THERMA:C28Execution','Execution/release/parameter identity mismatch.');
    sources=m.compatible_reference_sources;
    compatible=strcmp({sources.trajectory_sha256},p.source_trajectory_sha256) & ...
        strcmp({sources.manifest_sha256},p.reference_manifest_sha256) & ...
        strcmp({sources.signals_sha256},p.source_signals_sha256);
    assert(sum(compatible)==1,'THERMA:C28Source','Unverified original/extended reference extraction.');
    if j==1
        planFile=fullfile(root,'configs','references','c27_study.json');
        assert(strcmp(contract.plan_sha256,boptest_file_sha256(planFile)), ...
            'THERMA:C28Plan','Study plan hash differs.');
        studyPlan=jsondecode(fileread(planFile));
        assert(strcmp(expected.packet_sha256,studyPlan.no_solar_packet_sha256), ...
            'THERMA:C28Packet','Unexpected no-solar packet.');
    else
        assert(strcmp(expected.packet_sha256,studyPlan.solar_packet_sha256), ...
            'THERMA:C28Packet','Unexpected solar packet.');
    end
    assert(strcmp(p.reference_scenario_id,m.scenario.name) && ...
        strcmp(p.reference_version,m.boptest_commit) && strcmp(metadata.reference_version,m.boptest_commit) && ...
        strcmp(metadata.scenario_id,p.scenario_id) && ...
        strcmp(p.source_fmu_sha256,m.fmu_sha256) && ...
        p.time_origin_s==28252800 && p.evaluation_start_s==t(1) && p.evaluation_end_s==t(end), ...
        'THERMA:C28Scenario','Replay is not bound to this reference trajectory and interval.');
    assert(strcmp(metadata.csv_sha256,boptest_file_sha256(fullfile(folder,'evaluation.csv'))), ...
        'THERMA:C28Hash','Evaluation metadata hash mismatch.');
    spec=metadata.signals(strcmp({metadata.signals.quantity},'air_temperature'));
    assert(numel(spec)==1 && strcmp(spec.interpolation,'linear'), ...
        'THERMA:C28Quantity','Missing/ambiguous air temperature or wrong interpolation.');
    column='air_temperature'; if isfield(spec,'column'), column=spec.column; end
    data=readTemperatureTable(fullfile(folder,'evaluation.csv'));
    assert(data.time_s(1)==t(1) && data.time_s(end)==t(end), ...
        'THERMA:C28Coverage','Evaluation endpoints differ; no automatic time shift.');
    [values(:,j),summaries{j}]=boptest_temperature_metrics(data.time_s,data.(column),spec.unit,t,reference,spec.quantity);
    provenance.(ids{j})=struct('completion_sha256',item.completion_sha256, ...
        'evaluation_sha256',metadata.csv_sha256,'samples',height(data), ...
        'maximum_sample_gap_s',max(diff(data.time_s)), ...
        'matlab_version',r.matlab_version,'packet_sha256',r.replay_packet_sha256);
    reports{j}=r;
end
assert(strcmp(reports{1}.driver_source_sha256,reports{2}.driver_source_sha256) && ...
    strcmp(reports{1}.model_version,reports{2}.model_version) && ...
    isequal(reports{1}.solver,reports{2}.solver), ...
    'THERMA:C28Control','Controlled implementation/solver differs between experiments.');
output=tempname(fullfile(root,'outputs','boptest','c28')); mkdir(output);
errors=values-reference; days=(t-t(1))/86400;
fig=figure('Color','w'); plot(days,reference,'k','LineWidth',1.5); hold on;
plot(days,values(:,1),'b','LineWidth',1.1); plot(days,values(:,2),'r','LineWidth',1.1);
grid on; xlabel('Evaluation time (days)'); ylabel('Indoor air temperature (°C)');
title('THERMA C2.7 versus BOPTEST: prescribed-heating thermal-zone response');
legend('BOPTEST air','THERMA no solar','THERMA solar','Location','best');
exportgraphics(fig,fullfile(output,'temperature_comparison.png'),'Resolution',300);
savefig(fig,fullfile(output,'temperature_comparison.fig'));
fig=figure('Color','w'); plot(days,errors(:,1),'b',days,errors(:,2),'r','LineWidth',1.1);
grid on; xlabel('Evaluation time (days)'); ylabel('THERMA minus BOPTEST (°C)');
legend('No solar','Solar','Location','best'); title('Native 30-second reference-grid errors');
exportgraphics(fig,fullfile(output,'temperature_errors.png'),'Resolution',300);
savefig(fig,fullfile(output,'temperature_errors.fig'));
result=struct2table([summaries{:}]); result.experiment=ids';
writetable(result,fullfile(output,'metrics.csv'));
[worst,where]=max(abs(errors),[],1);
daily=[];
for day=0:13
    mask=days>=day & days<day+1; if day==13, mask=days>=day & days<=14; end
    for j=1:2
        e=errors(mask,j); daily=[daily; day j numel(e) mean(abs(e)) sqrt(mean(e.^2)) max(abs(e)) mean(e)]; %#ok<AGROW>
    end
end
writetable(array2table(daily,'VariableNames',{'day_zero_based','experiment_index','samples','MAE_degC', ...
    'RMSE_degC','maximum_absolute_error_degC','bias_degC'}),fullfile(output,'daily_metrics.csv'));
prior=jsondecode(fileread(fullfile(root,'docs','results','c26c','provenance.json')));
lineageReview=strcmp(provenance.solar_30.evaluation_sha256,prior.attachments.evaluation_csv.sha256);
provenance.prior_solar_csv_identity=lineageReview;
write_boptest_json(fullfile(output,'comparison_provenance.json'),provenance);
fid=fopen(fullfile(output,'validation_report.md'),'w'); assert(fid>=0); cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'# C2.8 controlled thermal-zone comparison\n\nExecuted comparison in MATLAB %s.\n',version);
fprintf(fid,'40321 common 30 s air-temperature samples; 7-day warm-up excluded. Bias = THERMA minus BOPTEST.\n');
fprintf(fid,'\nNo-solar MAE %.9g °C, RMSE %.9g °C; solar MAE %.9g °C, RMSE %.9g °C.\n', ...
    result.MAE_degC(1),result.RMSE_degC(1),result.MAE_degC(2),result.RMSE_degC(2));
fprintf(fid,'Signed solar-minus-no-solar changes: MAE %.9g °C; RMSE %.9g °C (negative means improvement).\n', ...
    diff(result.MAE_degC),diff(result.RMSE_degC));
fprintf(fid,'Worst no-solar/solar absolute errors %.9g / %.9g °C at evaluation days %.9g / %.9g.\n', ...
    worst(1),worst(2),days(where(1)),days(where(2)));
fprintf(fid,['\nThis tests reduced-zone response to prescribed BOPTEST radiator heating, not independent hydronic prediction or real-world validation.\n' ...
    'Hypotheses, not demonstrated causes: initial-state reduction, omitted window/airflow physics and solar allocation differences.\n' ...
    'Next: review daily errors, controlled convergence and event energy closure before selecting new physics. No calibration performed.\n']);
if lineageReview
    fprintf(fid,['\nExecution-lineage review required: uploaded solar CSV matches preserved C2.6C R2021a evidence, ' ...
        'while supplied reports state R2024a. This does not establish an independent fresh same-release run.\n']);
end
fprintf('C2.8 comparison saved to %s\n',output);
end

function data=readTemperatureTable(file)
fid=fopen(file,'r'); assert(fid>=0,'THERMA:C28Missing','Cannot read %s',file);
cleanup=onCleanup(@() fclose(fid)); header=fgetl(fid);
assert(ischar(header),'THERMA:C28Header','Missing CSV header.');
columns=strsplit(header,',');
assert(numel(unique(columns))==numel(columns),'THERMA:C28Header','Duplicate CSV columns.');
data=readtable(file,'VariableNamingRule','preserve');
end
