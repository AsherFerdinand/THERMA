function [values,result] = boptest_temperature_metrics(time,temperature,unit,target,reference,quantity)
%BOPTEST_TEMPERATURE_METRICS Strict air comparison, linear alignment, no extrapolation.
assert(strcmp(quantity,'air_temperature'),'THERMA:C28Quantity', ...
    'Operative temperature is not like-for-like indoor air validation.');
assert(isvector(time) && isvector(temperature) && numel(time)==numel(temperature) && ...
    numel(time)>=2 && all(isfinite(time)) && all(isfinite(temperature)) && ...
    all(diff(time)>0),'THERMA:C28Samples','Missing, duplicate, unordered or nonfinite samples.');
assert(isvector(target) && numel(target)==numel(reference) && numel(target)>=2 && ...
    all(isfinite(target)) && all(isfinite(reference)) && all(diff(target)>0), ...
    'THERMA:C28Reference','Invalid reference samples.');
assert(target(1)>=time(1) && target(end)<=time(end),'THERMA:C28Coverage','Extrapolation forbidden.');
if strcmp(unit,'K'), temperature=temperature-273.15;
else, assert(strcmp(unit,'degC'),'THERMA:C28Units','Expected K or degC.'); end
values=interp1(time(:),temperature(:),target(:),'linear');
errors=values-reference(:);
result=struct('sample_count',numel(errors),'MAE_degC',mean(abs(errors)), ...
    'RMSE_degC',sqrt(mean(errors.^2)),'maximum_absolute_error_degC',max(abs(errors)), ...
    'bias_degC',mean(errors));
end
