function [metadata,data] = load_boptest_replay(file)
%LOAD_BOPTEST_REPLAY Validate a partial forcing packet; never invent missing inputs.
metadata = jsondecode(fileread(file));
assert(ismember(metadata.schema_version,[1 2]) && strcmp(metadata.status,'partial_replay_ready') && ...
    strcmp(metadata.classification,'exploratory_comparison'), ...
    'THERMA:ReplaySchema','Expected explicit exploratory partial replay packet.');
solarMode = metadata.schema_version==2;
if solarMode
    assert(strcmp(metadata.replay_mode,'solar_resolved_partial') && ...
        isequal(string(metadata.c2_solar_order(:)), ...
        ["south";"north";"east";"west";"roof";"floor"]) && ...
        isequal(string(metadata.solar_surface_order(:)), ...
        ["south";"west";"north";"east";"floor";"roof";"glazing"]), ...
        'THERMA:ReplaySolarOrder','Unsupported solar mode or surface order.');
    assert(strcmp(metadata.source_fmu_sha256, ...
        '365b3085d97cc4620c06b6036156126a056d7f160fcc4f181d6b2fac4b05743b') && ...
        strcmp(metadata.reference_version,'a29024f8c453517ccbd1186006a3fa6af8de1ae2') && ...
        strcmp(metadata.reference_scenario_id,metadata.source_scenario.name), ...
        'THERMA:ReplayReference','Incompatible pinned reference identity.');
end
folder = fileparts(file); csvFile = fullfile(folder,'inputs.csv');
assert(strcmp(boptest_file_sha256(csvFile),metadata.inputs_sha256), ...
    'THERMA:ReplayHash','Replay CSV hash mismatch.');
fid = fopen(csvFile,'r'); assert(fid>=0,'THERMA:ReplayRead','Cannot read inputs.');
cleanup = onCleanup(@() fclose(fid)); header = strsplit(strtrim(fgetl(fid)),',');
expected = [{'time_s'},cellstr(compose('input_%02d',1:11))];
assert(isequal(header,expected),'THERMA:ReplayColumns','Unexpected input port order.');
data = readmatrix(csvFile,'NumHeaderLines',1);
assert(size(data,2)==12 && size(data,1)>=2 && all(isfinite(data),'all') && ...
    all(diff(data(:,1))>=0) && data(1,1)==0 && data(end,1)==metadata.duration_s, ...
    'THERMA:ReplayData','Expected finite full-period data beginning at relative time zero.');
assert(numel(metadata.channels)==11,'THERMA:ReplayChannels','Expected eleven channels.');
expectedQuantities = {'outdoor_temperature','delivered_heating_convective_power', ...
    'delivered_heating_radiative_power','internal_convective_power','internal_radiative_power'};
for j = 1:11
    if iscell(metadata.channels), channel = metadata.channels{j};
    else, channel = metadata.channels(j); end
    assert(strcmp(channel.column,sprintf('input_%02d',j)), ...
        'THERMA:ReplayChannels','Channel index/name mismatch.');
    if j==1, unit = 'K'; else, unit = 'W'; end
    assert(strcmp(channel.unit,unit) && ...
        ismember(string(channel.interpolation),["linear","previous"]), ...
        'THERMA:ReplayUnits','Unsupported channel unit/interpolation.');
    if solarMode
        if j==1, policy='linear'; else, policy='previous'; end
        assert(strcmp(channel.interpolation,policy),'THERMA:ReplayPolicy', ...
            'Solar v2 requires outdoor linear and all power channels held.');
    end
    if j<=5
        assert(strcmp(channel.quantity,expectedQuantities{j}), ...
            'THERMA:ReplayQuantity','Wrong physical quantity at port %d.',j);
    elseif solarMode
        face = metadata.c2_solar_order{j-5};
        assert(strcmp(channel.quantity,['absorbed_solar_' face '_power']) && ...
            strcmp(channel.status,'derived_reference') && ...
            all(data(:,j+1)>=-1e-8),'THERMA:ReplaySolar', ...
            'Expected signed source-derived opaque solar power in W.');
    else
        assert(strcmp(channel.quantity,sprintf('omitted_absorbed_solar_%d',j-5)) && ...
            all(data(:,j+1)==0),'THERMA:ReplaySolar','Partial experiment must explicitly omit solar.');
    end
    if strcmp(channel.interpolation,'linear')
        repeated = diff(data(:,1))==0;
        changes = diff(data(:,j+1));
        assert(all(changes(repeated)==0),'THERMA:ReplayJump', ...
            'Continuous channel has a duplicate-time jump; no interpolation across it.');
    end
end
if solarMode
    assert(numel(metadata.initial_conditions.observed_temperature_K)==28 && ...
        isequal(metadata.initial_conditions.temperature_K(:), ...
        metadata.initial_conditions.observed_temperature_K(:)), ...
        'THERMA:ReplayInitial','Declared start differs from observed source temperatures.');
    assert(all(diff(data(:,1))==30),'THERMA:ReplaySolarGrid', ...
        'Solar v2 requires complete unique 30-second timestamps.');
    assert(strcmp(boptest_file_sha256(fullfile(folder,'solar_sources.csv')), ...
        metadata.solar_sources_sha256),'THERMA:ReplaySolarHash', ...
        'Original solar-source samples hash mismatch.');
    assert(numel(metadata.solar_signals)==31,'THERMA:ReplaySolarSources', ...
        'Expected original 31 solar-source signal definitions.');
    for k = 1:31
        source = metadata.solar_signals(k);
        if k>=4 && k<=24, sourceUnit='1'; else, sourceUnit='W'; end
        assert(strcmp(source.unit,sourceUnit),'THERMA:ReplaySolarUnits', ...
            'Solar source must use W and dimensionless allocation weights.');
    end
    sevenFile = fullfile(folder,'solar_seven.csv');
    assert(strcmp(boptest_file_sha256(sevenFile),metadata.solar_seven_sha256), ...
        'THERMA:ReplaySolarHash','Seven-surface provenance hash mismatch.');
    fidSeven = fopen(sevenFile,'r');
    assert(fidSeven>=0,'THERMA:ReplayRead','Cannot read seven-surface solar.');
    cleanupSeven = onCleanup(@() fclose(fidSeven));
    sevenHeader = strsplit(strtrim(fgetl(fidSeven)),',');
    assert(isequal(sevenHeader,{'time_s','south','west','north','east','floor','roof','glazing'}), ...
        'THERMA:ReplaySolarOrder','Seven-surface CSV order mismatch.');
    seven = readmatrix(sevenFile,'NumHeaderLines',1);
    assert(isequal(size(seven),[size(data,1) 8]) && all(isfinite(seven),'all') && ...
        isequal(seven(:,1),data(:,1)+metadata.time_origin_s) && ...
        all(seven(:,2:8)>=-1e-8,'all') && ...
        max(abs(data(:,7:12)-seven(:,[2 4 5 3 7 6])),[],'all')<=1e-8, ...
        'THERMA:ReplaySolarMapping','Opaque powers disagree with preserved seven-surface data.');
end
assert(numel(metadata.initial_conditions.temperature_K)==28 && ...
    all(isfinite(metadata.initial_conditions.temperature_K)) && ...
    all(metadata.initial_conditions.temperature_K>0), ...
    'THERMA:ReplayInitial','Explicit 28-state positive Kelvin initial vector required.');
assert(strcmp(metadata.initial_conditions.status, ...
    'provisional_uniform_declared_start_not_full_FMU_state'), ...
    'THERMA:ReplayInitial','This runner supports declared partial initialization only.');
assert(metadata.evaluation_start_s>=metadata.time_origin_s && ...
    metadata.evaluation_end_s==metadata.time_origin_s+metadata.duration_s, ...
    'THERMA:ReplayPeriod','Evaluation/warm-up boundaries disagree.');
end
