function S=c35_steady_diagnostics(Z,P,I)
%C35_STEADY_DIAGNOSTICS Conditional all-on linear-network analysis, not a simulation.
[A,B,capacities]=boptest_zone_analytical_network(Z); n=size(A,1);
b=(1-P.radiative_fraction)*B(:,2)+P.radiative_fraction*B(:,3);
% Deliberately NO solar for this conditional static reference, even in E_solar.
f=B(:,1)*I.outdoor_K+B(:,4)*I.internal_convective_W+B(:,5)*I.internal_radiative_W;
free=-(A\f); response=-(A\b); R=response(end);
assert(isfinite(R) && R>0,'THERMA:C35Steady','Invalid steady heat response.');
H=P.nominal_flow_kg_s*P.water_cp_J_kgK; effective=H*P.UA_W_K/(H+P.UA_W_K);
Qrequired=(I.setpoint_K-free(end))/R;
Qavailable=effective*(I.supply_K-I.setpoint_K);
air=(free(end)+R*effective*I.supply_K)/(1+R*effective);
plant=[A-b*P.UA_W_K*[zeros(1,n-1) 1],b*P.UA_W_K; ...
    zeros(1,n-1) P.UA_W_K/P.capacitance_J_K -(H+P.UA_W_K)/P.capacitance_J_K];
rate=max(real(eig(plant))); slow=-1;
if rate<0, slow=-1/rate; end
S=struct('classification','conditional_all_on_steady_model_diagnostic_not_observed_result', ...
    'solar_assumption','zero solar static reference, not the time-varying E profile', ...
    'zone_heat_response_K_W',R,'required_room_heat_at_setpoint_W',Qrequired, ...
    'available_full_open_heat_at_setpoint_W',Qavailable,'capacity_margin_at_setpoint_W',Qavailable-Qrequired, ...
    'all_on_steady_air_degC',air-273.15,'water_conductance_W_K',H, ...
    'effective_emitter_conductance_W_K',effective,'largest_real_eigenvalue_per_s',rate, ...
    'stable_all_on_linear_plant',rate<0,'slowest_time_constant_s',slow, ...
    'total_zone_capacity_J_K',sum(capacities), ...
    'caution','Fixed full opening and air-radiant proxy; thermostat, finite warmup and solar dynamics not represented by this steady result.');
end
