function [model, modelFile] = build_room_heating_model(p)
%BUILD_ROOM_HEATING_MODEL Build a NEW two-state Simulink thermal benchmark.
% Requires MATLAB/Simulink, not Simscape. Does not open/change the thesis model.
% Fill room_heating_parameters first. See docs/ROOM_REFERENCE_MODEL.md.
arguments
    p (1,1) struct
end
positive = ["room_capacity_J_K", "radiator_capacity_J_K", "radiator_UA_W_K", ...
    "water_cp_J_kg_K", "open_flow_kg_s", "initial_room_K", "initial_radiator_K", ...
    "outdoor_K", "supply_K", "setpoint_K", "thermostat_deadband_K", ...
    "duration_s", "max_step_s", "relative_tolerance", "absolute_tolerance_K", ...
    "design_indoor_K", "design_outdoor_K"];
for name = positive
    assert(isfield(p, name), 'THERMA:MissingParameter', 'Missing parameter: %s', name);
    validateattributes(p.(name), {'numeric'}, {'real', 'finite', 'scalar', 'positive'}, ...
        mfilename, char(name));
end
for name = ["design_transmission_loss_W", "design_ventilation_loss_W"]
    assert(isfield(p, name), 'THERMA:MissingParameter', 'Missing parameter: %s', name);
    validateattributes(p.(name), {'numeric'}, {'real', 'finite', 'scalar', 'nonnegative'}, ...
        mfilename, char(name));
end
for name = ["provenance", "standard_reference", "national_rules", "load_calculation_reference"]
    assert(isfield(p, name) && (ischar(p.(name)) || isstring(p.(name))) ...
        && isscalar(string(p.(name))) && strlength(strtrim(string(p.(name)))) > 0, ...
        'THERMA:MissingProvenance', 'Provide a documented reference for p.%s.', name);
end
assert(p.design_indoor_K > p.design_outdoor_K, 'THERMA:InvalidDesignTemperature', ...
    'Design indoor temperature must exceed design outdoor temperature.');
% This reduction consumes externally checked EN 12831 design results. It does
% NOT perform an EN 12831 calculation or reproduce its separate boundary paths.
p.room_loss_W_K = (p.design_transmission_loss_W + p.design_ventilation_loss_W) ...
    / (p.design_indoor_K - p.design_outdoor_K);
assert(isfinite(p.room_loss_W_K), 'THERMA:InvalidConductance', 'Invalid equivalent conductance.');
assert(p.setpoint_K > p.thermostat_deadband_K/2, 'THERMA:InvalidBand', ...
    'The lower thermostat threshold must be above absolute zero.');
assert(abs(p.setpoint_K - p.initial_room_K) > p.thermostat_deadband_K/2, ...
    'THERMA:AmbiguousInitialValve', ...
    'Initial room temperature must be outside the thermostat band for an unambiguous initial command.');
assert(p.relative_tolerance < 1, 'THERMA:InvalidTolerance', 'Relative tolerance must be below 1.');

model = 'therma_room_reference';
assert(exist('new_system', 'file') ~= 0, 'THERMA:NoSimulink', 'Simulink is required.');
assert(~bdIsLoaded(model), 'THERMA:AlreadyLoaded', ...
    'Close your existing therma_room_reference model before building a new one.');
projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outputRoot = fullfile(projectRoot, 'outputs', 'room_reference');
if ~isfolder(outputRoot), mkdir(outputRoot); end
runDir = tempname(outputRoot);
mkdir(runDir);
modelFile = fullfile(runDir, [model '.slx']);
load_system('simulink'); % Only the trusted built-in library is loaded.
new_system(model);
try
    workspace = get_param(model, 'ModelWorkspace');
    assignin(workspace, 'p', p); % Stored in the NEW model, never in the base workspace.
    set_param(model, 'SolverType', 'Variable-step', 'Solver', 'ode15s', ...
        'StartTime', '0', 'StopTime', num2str(p.duration_s, 17), ...
        'MaxStep', num2str(p.max_step_s, 17), ...
        'RelTol', num2str(p.relative_tolerance, 17), ...
        'AbsTol', num2str(p.absolute_tolerance_K, 17), 'ReturnWorkspaceOutputs', 'on');

    % Empty subsystems: no default input-to-output wires to remove.
    add_block('built-in/Subsystem', [model '/Room'], 'Position', [550 150 710 270]);
    add_block('built-in/Subsystem', [model '/Radiator'], 'Position', [300 150 460 270]);
    room = [model '/Room'];
    radiator = [model '/Radiator'];

    % C_room*dT_room/dt = Q_radiator - G_loss*(T_room - T_outdoor).
    add_block('simulink/Sources/In1', [room '/Q_radiator_W'], 'Port', '1', 'Position', [20 30 50 50]);
    add_block('simulink/Sources/In1', [room '/T_outdoor_K'], 'Port', '2', 'Position', [20 140 50 160]);
    add_block('simulink/Math Operations/Sum', [room '/Delta_T_loss'], ...
        'Inputs', '+-', 'Position', [110 100 135 135]);
    add_block('simulink/Math Operations/Gain', [room '/G_loss'], ...
        'Gain', 'p.room_loss_W_K', 'Position', [180 95 250 135]);
    add_block('simulink/Math Operations/Sum', [room '/Net_heat_W'], ...
        'Inputs', '+-', 'Position', [300 30 325 65]);
    add_block('simulink/Math Operations/Gain', [room '/Inverse_capacity'], ...
        'Gain', '1/p.room_capacity_J_K', 'Position', [370 25 460 65]);
    add_block('simulink/Continuous/Integrator', [room '/Temperature_K'], ...
        'InitialCondition', 'p.initial_room_K', 'Position', [510 25 550 65]);
    add_block('simulink/Sinks/Out1', [room '/T_room_K'], 'Position', [620 30 650 50]);
    connect(room, {'Q_radiator_W/1','Net_heat_W/1'; 'Temperature_K/1','Delta_T_loss/1'; ...
        'T_outdoor_K/1','Delta_T_loss/2'; 'Delta_T_loss/1','G_loss/1'; ...
        'G_loss/1','Net_heat_W/2'; 'Net_heat_W/1','Inverse_capacity/1'; ...
        'Inverse_capacity/1','Temperature_K/1'; 'Temperature_K/1','T_room_K/1'});

    % C_rad*dT_water/dt = m_dot*cp*(T_supply - T_water) - UA*(T_water - T_room).
    add_block('simulink/Sources/In1', [radiator '/T_room_K'], 'Port', '1', 'Position', [20 180 50 200]);
    add_block('simulink/Sources/In1', [radiator '/T_supply_K'], 'Port', '2', 'Position', [20 30 50 50]);
    add_block('simulink/Sources/In1', [radiator '/Mass_flow_kg_s'], 'Port', '3', 'Position', [20 95 50 115]);
    add_block('simulink/Math Operations/Sum', [radiator '/Delta_T_supply'], ...
        'Inputs', '+-', 'Position', [100 30 125 65]);
    add_block('simulink/Math Operations/Product', [radiator '/Flow_times_deltaT'], ...
        'Inputs', '**', 'Position', [175 30 205 65]);
    add_block('simulink/Math Operations/Gain', [radiator '/Water_cp'], ...
        'Gain', 'p.water_cp_J_kg_K', 'Position', [250 25 320 65]);
    add_block('simulink/Math Operations/Sum', [radiator '/Net_heat_W'], ...
        'Inputs', '+-', 'Position', [370 30 395 65]);
    add_block('simulink/Math Operations/Gain', [radiator '/Inverse_capacity'], ...
        'Gain', '1/p.radiator_capacity_J_K', 'Position', [440 25 530 65]);
    add_block('simulink/Continuous/Integrator', [radiator '/Temperature_K'], ...
        'InitialCondition', 'p.initial_radiator_K', 'Position', [580 25 620 65]);
    add_block('simulink/Math Operations/Sum', [radiator '/Delta_T_room'], ...
        'Inputs', '+-', 'Position', [100 180 125 215]);
    add_block('simulink/Math Operations/Gain', [radiator '/UA'], ...
        'Gain', 'p.radiator_UA_W_K', 'Position', [175 180 255 220]);
    add_block('simulink/Sinks/Out1', [radiator '/Q_radiator_W'], 'Port', '1', 'Position', [320 185 350 205]);
    add_block('simulink/Sinks/Out1', [radiator '/T_radiator_K'], 'Port', '2', 'Position', [690 30 720 50]);
    connect(radiator, {'T_supply_K/1','Delta_T_supply/1'; 'Temperature_K/1','Delta_T_supply/2'; ...
        'Delta_T_supply/1','Flow_times_deltaT/1'; 'Mass_flow_kg_s/1','Flow_times_deltaT/2'; ...
        'Flow_times_deltaT/1','Water_cp/1'; 'Water_cp/1','Net_heat_W/1'; ...
        'UA/1','Net_heat_W/2'; 'Net_heat_W/1','Inverse_capacity/1'; ...
        'Inverse_capacity/1','Temperature_K/1'; 'Temperature_K/1','T_radiator_K/1'; ...
        'Temperature_K/1','Delta_T_room/1'; 'T_room_K/1','Delta_T_room/2'; ...
        'Delta_T_room/1','UA/1'; 'UA/1','Q_radiator_W/1'});

    add_block('simulink/Sources/Constant', [model '/Outdoor_K'], ...
        'Value', 'p.outdoor_K', 'Position', [490 305 570 335]);
    add_block('simulink/Sources/Constant', [model '/Supply_K'], ...
        'Value', 'p.supply_K', 'Position', [100 170 180 200]);
    add_block('simulink/Sources/Constant', [model '/Setpoint_K'], ...
        'Value', 'p.setpoint_K', 'Position', [40 35 120 65]);
    add_block('simulink/Math Operations/Sum', [model '/Temperature_error_K'], ...
        'Inputs', '+-', 'Position', [180 35 205 70]);
    add_block('simulink/Discontinuities/Relay', [model '/Thermostat'], ...
        'OnSwitchValue', 'p.thermostat_deadband_K/2', ...
        'OffSwitchValue', '-p.thermostat_deadband_K/2', ...
        'OnOutputValue', '1', 'OffOutputValue', '0', 'Position', [260 30 320 70]);
    add_block('simulink/Math Operations/Gain', [model '/Ideal_valve_flow_kg_s'], ...
        'Gain', 'p.open_flow_kg_s', 'Position', [380 30 490 70]);
    add_block('simulink/Signal Routing/Mux', [model '/Signals'], ...
        'Inputs', '5', 'Position', [800 130 810 290]);
    add_block('simulink/Sinks/To Workspace', [model '/Log'], ...
        'VariableName', 'therma_signals', 'SaveFormat', 'Timeseries', ...
        'MaxDataPoints', 'inf', 'Decimation', '1', 'Position', [880 190 990 230]);
    connect(model, {'Setpoint_K/1','Temperature_error_K/1'; 'Room/1','Temperature_error_K/2'; ...
        'Temperature_error_K/1','Thermostat/1'; 'Thermostat/1','Ideal_valve_flow_kg_s/1'; ...
        'Ideal_valve_flow_kg_s/1','Radiator/3'; 'Supply_K/1','Radiator/2'; ...
        'Room/1','Radiator/1'; 'Radiator/1','Room/1'; 'Outdoor_K/1','Room/2'; ...
        'Room/1','Signals/1'; 'Radiator/2','Signals/2'; 'Radiator/1','Signals/3'; ...
        'Ideal_valve_flow_kg_s/1','Signals/4'; 'Thermostat/1','Signals/5'; 'Signals/1','Log/1'});
    save_system(model, modelFile); % New file in a unique ignored output directory only.
catch problem
    close_system(model, 0);
    rethrow(problem);
end
open_system(model);
fprintf('Created %s\nNot a standards-certified or thesis-validated model.\n', modelFile);
end

function connect(system, pairs)
for k = 1:size(pairs, 1)
    add_line(system, pairs{k, 1}, pairs{k, 2}, 'autorouting', 'on');
end
end
