function D=assess_c34(time,y,names,I,P)
%ASSESS_C34 Actual logged balances; duplicate event timestamps remain ordered.
assert(isvector(time) && size(y,1)==numel(time) && size(y,2)==numel(names) && ...
    numel(time)>=2 && all(isfinite(time)) && all(isfinite(y),'all') && all(diff(time)>=0), ...
    'THERMA:C34Finite','Nonfinite/unordered/malformed integration output.');
assert(abs(time(1))<1e-8 && abs(time(end)-I.duration_s)<1e-6, ...
    'THERMA:C34Coverage','Integration output does not cover the requested interval.');
s=@(name) y(:,find(strcmp(names,name),1));
zoneChange=s('zone_stored_J')-y(1,strcmp(names,'zone_stored_J'));
radChange=s('radiator_stored_J')-y(1,strcmp(names,'radiator_stored_J'));
radError=s('water_J')-s('delivered_J')-radChange;
combinedError=s('external_J')-zoneChange-radChange;
throughput=max([1;abs(s('water_J'));abs(s('delivered_J'));abs(s('external_J'));abs(zoneChange);abs(radChange)]);
budget=I.checks.energy_absolute_J+I.checks.energy_relative*throughput;
demand=s('demand'); opening=s('opening');
D=struct('status','checks_not_yet_passed','samples',numel(time),'duplicate_event_times',sum(diff(time)==0), ...
    'radiator_integrated_error_max_J',max(abs(radError)), ...
    'combined_integrated_error_max_J',max(abs(combinedError)), ...
    'combined_integrated_error_final_J',combinedError(end),'energy_budget_J',budget, ...
    'radiator_residual_max_W',max(abs(s('radiator_residual_W'))), ...
    'zone_residual_max_W',max(abs(s('zone_residual_W'))), ...
    'combined_residual_max_W',max(abs(s('combined_residual_W'))), ...
    'heating_port_mismatch_max_W',max(abs(s('zone_heating_W')-s('delivered_W'))), ...
    'heat_partition_mismatch_max_W',max(abs(s('convective_W')+s('radiative_W')-s('delivered_W'))), ...
    'air_min_K',min(s('air_K')),'air_max_K',max(s('air_K')), ...
    'radiator_min_K',min(s('radiator_K')),'radiator_max_K',max(s('radiator_K')), ...
    'opening_min',min(opening),'opening_max',max(opening), ...
    'demand_transitions',sum(diff(demand)~=0),'delivered_final_J',s('delivered_J'), ...
    'water_final_J',s('water_J'),'maximum_abs_delivered_W',max(abs(s('delivered_W'))));
D.delivered_final_J=D.delivered_final_J(end); D.water_final_J=D.water_final_J(end);
D.checks=struct('energy',max(abs(radError))<=budget && max(abs(combinedError))<=budget, ...
    'instantaneous',max([D.radiator_residual_max_W D.zone_residual_max_W D.combined_residual_max_W]) ...
        <=I.checks.instantaneous_balance_W, ...
    'no_double_heating',D.heating_port_mismatch_max_W<=I.checks.instantaneous_balance_W && ...
        D.heat_partition_mismatch_max_W<=I.checks.instantaneous_balance_W, ...
    'actuator',all(opening>=-1e-9 & opening<=1+1e-9) && all(ismember(demand,[0 1])));
changes=time([false;diff(demand)~=0]);
D.checks.controller_timing=all(abs(changes/P.controller_period_s-round(changes/P.controller_period_s))<1e-6);
low=min([I.outdoor_K I.initial_zone_K I.initial_radiator_K I.supply_K]);
high=max([I.outdoor_K I.initial_zone_K I.initial_radiator_K I.supply_K]);
temperatures=[s('air_K') s('radiator_K') s('opaque_mean_K')];
D.checks.positive_temperatures=all(temperatures>0,'all');
D.passive_zero_gain_envelope_checked=I.internal_convective_W==0 && I.internal_radiative_W==0 && all(I.solar_W==0);
D.checks.passive_envelope=true; D.checks.power_bounds=true;
if D.passive_zero_gain_envelope_checked
    D.checks.passive_envelope=all(temperatures>=low-I.checks.temperature_envelope_margin_K & ...
        temperatures<=high+I.checks.temperature_envelope_margin_K,'all');
    D.checks.power_bounds=max(abs(s('delivered_W')))<=P.UA_W_K*(high-low)+1e-5 && ...
        max(abs(s('water_W')))<=P.nominal_flow_kg_s*P.water_cp_J_kgK*(high-low)+1e-5;
end
D.checks.forward_mass_flow=all(s('mass_flow_kg_s')>=-1e-12 & s('mass_flow_kg_s')<=P.nominal_flow_kg_s+1e-12);
if all(structfun(@(v) logical(v),D.checks)), D.status='integration_numerical_checks_passed';
else, D.status='integration_numerical_checks_failed'; end
D.energy_method='Native continuous energy integrators; initial storage offsets removed; no sparse-log quadrature';
D.interpretation='Numerical consistency only; no BOPTEST, radiator sizing, comfort or real-world validation claim';
end
