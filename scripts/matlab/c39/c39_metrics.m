function S=c39_metrics(temperature,heating,m)
%C39_METRICS Reuse C2.8 air metrics; signed previous-hold input energy audit.
assert(strcmp(m.temperature_quantity,'air_temperature') && strcmp(m.reference_temperature_source, ...
    'mod.case900Template.TAir') && strcmp(m.temperature_unit,'K') && strcmp(m.power_unit,'W') && ...
    strcmp(m.heating_quantity,'delivered_zone_heat') && ...
    strcmp(m.heating_source,'-(mod.rad.QCon_flow + mod.rad.QRad_flow)'), ...
    'THERMA:C39Quantity','Need corresponding indoor air in K and delivered-zone heat in W; operative is not air.');
assert(size(temperature,2)==4 && size(heating,2)==3 && ...
    all(isfinite(temperature),'all') && all(isfinite(heating),'all'), ...
    'THERMA:C39Data','Invalid derived comparison data.');
t=temperature(:,1); h=heating(:,1); a=m.scenario.evaluation_start_s; b=m.scenario.evaluation_end_s;
assert(numel(t)==m.sample_count && all(diff(t)==30) && all(diff(h)>0) && ...
    t(1)==a && t(end)==b && h(1)==a && h(end)==b, ...
    'THERMA:C39Time','Need matching absolute evaluation endpoints, native30s grid, no warm-up.');
[~,M]=boptest_temperature_metrics(t,temperature(:,2),'K',t,temperature(:,3)-273.15,'air_temperature');
E=struct('reference_30s_hold_kWh',sum(diff(t).*temperature(1:end-1,4))/3.6e6, ...
    'THERMA_logged_hold_kWh',sum(diff(h).*heating(1:end-1,2))/3.6e6, ...
    'reference_on_log_grid_hold_kWh',sum(diff(h).*heating(1:end-1,3))/3.6e6, ...
    'max_logged_input_discrepancy_W',max(abs(heating(:,2)-heating(:,3))));
assert(E.max_logged_input_discrepancy_W<=1e-7,'THERMA:C39Heating','Logged heating input differs from reference hold.');
S=struct('temperature',M,'heating',E,'new_simulations',0, ...
    'interpretation','Prescribed-input consistency only, not independent heating-system or real-world validation');
end
