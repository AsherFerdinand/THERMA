function S=c40_compare(baseline,current,period,duration)
%C40_COMPARE Fixed presentation-regression tolerances, not physical accuracy claims.
grid=(0:period:duration)';
assert(grid(end)==duration,'THERMA:C40Grid','Need full controller-period coverage.');
B=sample(baseline,grid,period); C=sample(current,grid,period);
S=struct('samples',numel(grid),'max_air_difference_K',max(abs(C(:,1)-B(:,1))), ...
    'max_power_difference_W',max(abs(C(:,2)-B(:,2))), ...
    'demand_samples_identical',isequal(C(:,3),B(:,3)), ...
    'baseline_transitions',baseline.full_day_metrics.thermostat_transitions, ...
    'current_transitions',current.full_day_metrics.thermostat_transitions, ...
    'baseline_delivered_kWh',baseline.full_day_metrics.delivered_kWh, ...
    'current_delivered_kWh',current.full_day_metrics.delivered_kWh);
S.energy_difference_kWh=S.current_delivered_kWh-S.baseline_delivered_kWh;
S.tolerances=struct('air_K',0.001,'power_W',0.5,'energy_kWh',0.001, ...
    'demand','Exact equality at every controller tick, and equal full-day transition counts');
S.passed=S.max_air_difference_K<=S.tolerances.air_K && S.max_power_difference_W<=S.tolerances.power_W && ...
    abs(S.energy_difference_kWh)<=S.tolerances.energy_kWh && S.demand_samples_identical && ...
    S.baseline_transitions==S.current_transitions;
S.method='Continuous air/power linearly aligned at controller ticks; post-event demand sampled without interpolation';
end
function values=sample(C,grid,period)
t=C.time(:); air=C.air_K(:); power=C.power_W(:); demand=C.demand(:);
assert(numel(t)>=2 && all([numel(air) numel(power) numel(demand)]==numel(t)) && ...
    all(isfinite([t air power demand]),'all') && all(diff(t)>=0) && t(1)==0 && t(end)==grid(end), ...
    'THERMA:C40Samples','Incomplete/nonfinite/unordered comparison trace.');
last=[diff(t)>0;true]; values=zeros(numel(grid),3);
values(:,1:2)=interp1(t(last),[air(last) power(last)],grid,'linear');
% Same post-event selection rule as the verified C3.5 controller audit.
tick=round(t/period); distance=abs(t-tick*period); eligible=find(distance<=1e-6);
ordered=sortrows([tick(eligible),distance(eligible),-eligible],[1 2 3]);
[keys,first]=unique(ordered(:,1),'first'); chosen=-ordered(first,3);
assert(isequal(keys,(0:numel(grid)-1)'),'THERMA:C40Ticks','Missing controller samples.');
values(:,3)=demand(chosen);
end
