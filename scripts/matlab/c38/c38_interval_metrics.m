function M=c38_interval_metrics(t,air,setpoint,energy,demand,deadband)
%C38_INTERVAL_METRICS Same2-24h window; native energy differences, time weighting.
t=t(:); air=air(:); setpoint=setpoint(:); energy=energy(:); demand=demand(:);
start=7200; stop=86400;
assert(numel(t)>=2 && all([numel(air) numel(setpoint) numel(energy) numel(demand)]==numel(t)) && ...
    all(isfinite([t air setpoint energy demand]),'all') && all(diff(t)>=0) && ...
    t(1)==0 && t(end)==stop && all(ismember(demand,[0 1])), ...
    'THERMA:C38Window','Expected complete finite ordered0-24h records.');
% Post-event values for interpolation; duplicate events have zero duration.
last=[diff(t)>0;true]; uniqueT=t(last); values=[air(last) setpoint(last) energy(last)];
inside=t>start & t<stop;
edge=interp1(uniqueT,values,[start;stop],'linear');
tw=[start;t(inside);stop]; aw=[edge(1,1);air(inside);edge(2,1)];
sw=[edge(1,2);setpoint(inside);edge(2,2)];
base=c35_time_metrics(tw,aw,sw,deadband);
change=diff(demand); eventTime=t(2:end); selected=eventTime>start & eventTime<=stop;
M=struct('interval_h',[2 24],'mean_room_degC',sum(diff(tw).*(aw(1:end-1)+aw(2:end))/2)/(stop-start)-273.15, ...
    'minimum_room_degC',base.minimum_air_degC,'maximum_room_degC',base.maximum_air_degC, ...
    'MAE_from_setpoint_K',base.tracking_MAE_K,'on_transitions',sum(change(selected)>0), ...
    'off_transitions',sum(change(selected)<0),'transitions',sum(change(selected)~=0), ...
    'delivered_2_24_kWh',(edge(2,3)-edge(1,3))/3.6e6, ...
    'delivered_0_24_kWh',(energy(end)-energy(1))/3.6e6, ...
    'full_day_transitions',sum(change~=0),'deadband_K',deadband, ...
    'method','Piecewise-linear temperature and native cumulative energy; switches in(2h,24h], excluding2h event');
end
