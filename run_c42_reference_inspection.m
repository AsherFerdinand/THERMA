function folder=run_c42_reference_inspection(rawFolder)
%RUN_C42_REFERENCE_INSPECTION Explicit missing-input mode, not a thermal simulation.
root=fileparts(mfilename('fullpath'));
addpath(fullfile(root,'scripts','matlab','boptest'));
file=fullfile(root,'configs','buildings','annex58_experiment1.json');
c=jsondecode(fileread(file));
assert(c.schema_version==1 && c.dataset.annex==58 && c.dataset.experiment==1, ...
    'THERMA:C42Identity','Need the separate Annex58 Experiment1 configuration, not Annex71.');
if nargin<1 || strlength(string(rawFolder))==0, rawFolder=fullfile(root,c.local_raw_directory); end
files=c.source_files; availability=cell(1,numel(files)); missing={};
for k=1:numel(files)
    name=files(k).filename;
    if strcmp(name,'Supplementary_file_structure')
        candidates=dir(fullfile(rawFolder,[name '*'])); present=any(~[candidates.isdir]);
    else, present=isfile(fullfile(rawFolder,name)); end
    availability{k}=struct('filename',name,'present_locally',present,'content_verified',false);
    if ~present, missing{end+1}=name; end %#ok<AGROW>
end
% File presence alone cannot certify a PDF, license, signal schema or measurements.
assert(~c.ready_for_simulink_implementation && strcmp(c.geometry.status,'not_extracted') && ...
    strcmp(c.measurements.status,'unavailable_not_inspected'), ...
    'THERMA:C42Review','This missing-input entry must be completed after authoritative extraction; do not flip readiness flags.');
parent=fullfile(root,'outputs','c4','c42'); if ~isfolder(parent), mkdir(parent); end
folder=tempname(parent); mkdir(folder);
summary=struct('status',c.status,'reference_doi',c.dataset.doi,'matlab_inspection_version',version, ...
    'configuration_sha256',boptest_file_sha256(file),'dataset_metadata_provenance',c.dataset.metadata_provenance, ...
    'licence_record',c.dataset.licence, ...
    'source_file_presence',{availability},'missing_local_files',{missing}, ...
    'approved_zone_records',numel(c.geometry.zones),'actual_zone_count_known',false, ...
    'verified_signals',numel(c.measurements.signals),'sampling_interval_s',[], ...
    'data_completeness','Unknown: no genuine measurements inspected; not0percent completeness', ...
    'temperature_units','Unknown until actual channel metadata is inspected', ...
    'heating_units','Unknown until actual channel metadata is inspected', ...
    'plot_created',false,'processed_measurements_created',false,'simulation_executed',false, ...
    'ready_for_house_implementation',false, ...
    'required_action','Provide the official PDF, archive structure and accessible original measurements for review. Present files remain unreviewed; no artificial reference generated.');
write_boptest_json(fullfile(folder,'inspection_summary.json'),summary);
fprintf('Annex58 Experiment1: BLOCKED, not a completed dataset integration.\nDOI: %s\n',c.dataset.doi);
fprintf('Zones and signal names/units are not verified. No temperature plot or synthetic data generated.\n');
if ~isempty(missing), fprintf('Missing locally: %s\n',strjoin(missing,', ')); end
fprintf('Even present files need authoritative extraction/review. Summary: %s\n',folder);
end
